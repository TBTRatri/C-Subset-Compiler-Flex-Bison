import os
import subprocess
import streamlit as st

st.set_page_config(
    page_title="C-Subset Compiler Front-End", page_icon="⚙️", layout="wide"
)

st.title("⚙️ C-Subset Compiler Front-End Explorer")
st.markdown(
    "Interactive Lexical and Syntax Analyzer powered by **Flex**, **Bison (Yacc)**, and a custom scoped **Symbol Table**."
)


@st.cache_resource
def build_compiler():
  """Compiles the Flex and Bison parser binary."""
  try:
    # 1. Run Bison
    subprocess.run(
        ["bison", "-d", "-y", "parser.y", "-o", "parser.tab.c"], check=True
    )
    # 2. Run Flex
    subprocess.run(["flex", "-o", "lex.yy.c", "lexer.l"], check=True)
    # 3. Link with g++
    subprocess.run(
        ["g++", "-w", "-o", "compiler", "parser.tab.c", "lex.yy.c"], check=True
    )
    return True, "Compiler built successfully!"
  except subprocess.CalledProcessError as e:
    return False, f"Build error: {str(e)}"
  except Exception as e:
    return False, f"Unexpected error: {str(e)}"


# Build status
with st.spinner("Initializing compiler binaries..."):
  success, msg = build_compiler()

if not success:
  st.error(msg)
  st.stop()

col_left, col_right = st.columns([1, 1])

# Default sample code
default_code = """int a, b, c;
float x, y;

int main() {
    a = 10;
    b = 20;
    c = a + b * 2;
    if (c > 30) {
        x = 3.14;
    }
    return 0;
}
"""

with col_left:
  st.subheader("Source Code Input")
  source_code = st.text_area(
      "Write or paste your C-subset code:",
      value=default_code,
      height=380,
      help="Input C code to run through the lexical and syntax parser.",
  )
  run_button = st.button("Parse & Analyze", type="primary")

with col_right:
  st.subheader("Compiler Output & Diagnostics")

  if run_button or source_code:
    # Write input to a temporary file
    with open("temp_input.txt", "w") as f:
      f.write(source_code)

    try:
      # Run the compiled binary
      result = subprocess.run(
          ["./compiler", "temp_input.txt"],
          capture_output=True,
          text=True,
          timeout=5,
      )

      # Check for output files generated by the parser or stdout
      tabs = st.tabs(["Standard Output", "Log & Parse Tree", "Errors"])

      with tabs[0]:
        if result.stdout.strip():
          st.code(result.stdout, language="text")
        else:
          st.info("No standard console output.")

      with tabs[1]:
        # If your parser outputs to a log or symbol table file (e.g. log.txt)
        if os.path.exists("log.txt"):
          with open("log.txt", "r") as f:
            st.code(f.read(), language="text")
        elif os.path.exists("symbol_table.txt"):
          with open("symbol_table.txt", "r") as f:
            st.code(f.read(), language="text")
        else:
          st.text(
              "Compilation completed. Check parser actions and terminal stdout."
          )

      with tabs[2]:
        if result.stderr.strip():
          st.error(result.stderr)
        elif os.path.exists("error.txt") and os.path.getsize("error.txt") > 0:
          with open("error.txt", "r") as f:
            st.error(f.read())
        else:
          st.success("No syntax errors detected! Grammar validation passed.")

    except subprocess.TimeoutExpired:
      st.error("Execution timed out.")
    except Exception as e:
      st.error(f"Execution error: {str(e)}")
